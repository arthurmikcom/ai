import { getSessionUser, isAdmin, type SessionUser } from "./auth";

export function jsonError(message: string, status: number): Response {
  return Response.json({ error: message }, { status });
}

/**
 * What a guest (chatting without an account) is told about everything else.
 * `code` "login" makes the UI offer to sign in or up; 403, not 401, so the
 * page isn't sent to the login screen by itself.
 */
export function loginRequired(message = "Войдите или зарегистрируйтесь — это бесплатно."): Response {
  return Response.json({ error: message, code: "login" }, { status: 403 });
}

/**
 * The signed-in user, or a response to return as-is: 401 without a session,
 * and for a guest unless the route lets guests in (`guest`: the chat and
 * what it needs).
 */
export async function requireUser(request: Request, opts: { guest?: boolean } = {}): Promise<SessionUser | Response> {
  const user = await getSessionUser(request.headers);
  if (!user) return jsonError("Войдите в аккаунт", 401);
  return user.isAnonymous && !opts.guest ? loginRequired() : user;
}

/**
 * A file couldn't be saved because no storage is connected: users are told
 * to try later, the site's admin what to connect.
 */
export function storageUnavailable(user: SessionUser, message: string): Response {
  return jsonError(
    isAdmin(user)
      ? "Фото и файлы не сохраняются: подключите хранилище в Vercel → Storage → Create → Blob (Private) → Connect, затем Redeploy."
      : message,
    503,
  );
}

/** The signed-in admin, or a 401/403 response to return as-is. */
export async function requireAdmin(request: Request): Promise<SessionUser | Response> {
  const user = await requireUser(request);
  if (user instanceof Response) return user;
  return isAdmin(user) ? user : jsonError("Только для администраторов", 403);
}

const ID_PATTERN = /^[\w-]{8,64}$/;

/** Ids are generated by the browser (UUIDs); accept only safe shapes. */
export function isValidId(value: unknown): value is string {
  return typeof value === "string" && ID_PATTERN.test(value);
}
